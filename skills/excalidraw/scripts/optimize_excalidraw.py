#!/usr/bin/env python3
"""
Optimize Excalidraw files by removing unnecessary fields to reduce file size.

Based on Excalidraw's restoreElements() which auto-fills missing properties:
- Removes isDeleted: true elements
- Removes auto-regenerated metadata (seed, version, versionNonce, updated)
- Removes null fields (except semantically important ones)
- Removes default false booleans (isDeleted, locked)
- Removes empty groupIds arrays
- Keeps boundElements (needed for text binding)
- Keeps frameId (frame membership)

Usage: python optimize_excalidraw.py <path-to-excalidraw-file> [--dry-run]
"""
import json
import sys
from pathlib import Path
from copy import deepcopy


# Fields that are auto-regenerated by restoreElements()
REMOVABLE_METADATA = {'seed', 'version', 'versionNonce', 'updated'}

# Fields that can be removed when they have default/null values
REMOVABLE_WHEN_NULL = {'link', 'roundness', 'startArrowhead', 'lastCommittedPoint'}

# Fields that can be removed when false (these are defaults)
REMOVABLE_WHEN_FALSE = {'isDeleted', 'locked'}

# Fields that can be removed when empty array
REMOVABLE_WHEN_EMPTY_ARRAY = {'groupIds'}

# Arrow-specific fields that can be removed when null
ARROW_REMOVABLE_WHEN_NULL = {'fixedSegments', 'startIsSpecial', 'endIsSpecial'}


def optimize_element(element: dict) -> dict:
    """Optimize a single element by removing unnecessary fields."""
    optimized = {}

    for key, value in element.items():
        # Skip metadata fields (will be regenerated)
        if key in REMOVABLE_METADATA:
            continue

        # Skip null fields that are removable
        if value is None and key in REMOVABLE_WHEN_NULL:
            continue

        # Skip arrow-specific null fields
        if value is None and key in ARROW_REMOVABLE_WHEN_NULL:
            continue

        # Skip default false booleans
        if value is False and key in REMOVABLE_WHEN_FALSE:
            continue

        # Skip empty arrays that are removable
        if isinstance(value, list) and len(value) == 0 and key in REMOVABLE_WHEN_EMPTY_ARRAY:
            continue

        optimized[key] = value

    return optimized


def optimize_excalidraw(file_path: str, dry_run: bool = False) -> dict:
    """
    Optimize an Excalidraw file by removing unnecessary fields.

    Args:
        file_path: Path to the .excalidraw file
        dry_run: If True, only analyze without modifying

    Returns:
        Statistics about the optimization
    """
    file_path = Path(file_path)

    if not file_path.exists():
        print(f"Error: File not found: {file_path}")
        sys.exit(1)

    # Read the JSON file
    print(f"Reading {file_path}...")
    with open(file_path, 'r', encoding='utf-8') as f:
        original_content = f.read()

    original_size = len(original_content)
    data = json.loads(original_content)

    # Count elements before cleanup
    original_count = len(data.get('elements', []))

    # Remove deleted elements first
    if 'elements' in data:
        data['elements'] = [
            el for el in data['elements']
            if not el.get('isDeleted', False)
        ]

    deleted_count = original_count - len(data['elements'])

    # Optimize remaining elements
    if 'elements' in data:
        data['elements'] = [optimize_element(el) for el in data['elements']]

    # Minimize appState (only keep essential display settings)
    if 'appState' in data:
        essential_app_state = {}
        for key in ['viewBackgroundColor', 'gridSize', 'gridColor']:
            if key in data['appState']:
                essential_app_state[key] = data['appState'][key]
        data['appState'] = essential_app_state if essential_app_state else {}

    # Serialize with minimal whitespace for size comparison
    optimized_content = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
    optimized_size = len(optimized_content)

    # For actual file, use readable formatting
    formatted_content = json.dumps(data, indent=2, ensure_ascii=False)
    formatted_size = len(formatted_content)

    # Calculate savings
    savings = original_size - formatted_size
    savings_pct = (savings / original_size) * 100 if original_size > 0 else 0

    min_savings = original_size - optimized_size
    min_savings_pct = (min_savings / original_size) * 100 if original_size > 0 else 0

    # Print summary
    print(f"\n{'[DRY RUN] ' if dry_run else ''}Optimization Summary:")
    print(f"  Original elements: {original_count}")
    print(f"  Removed (isDeleted=true): {deleted_count}")
    print(f"  Remaining elements: {len(data['elements'])}")
    print(f"\n  Original size: {original_size:,} bytes ({original_size/1024:.1f} KB)")
    print(f"  Optimized size (formatted): {formatted_size:,} bytes ({formatted_size/1024:.1f} KB)")
    print(f"  Savings: {savings:,} bytes ({savings_pct:.1f}%)")
    print(f"\n  Minified size: {optimized_size:,} bytes ({optimized_size/1024:.1f} KB)")
    print(f"  Max savings (minified): {min_savings:,} bytes ({min_savings_pct:.1f}%)")

    if not dry_run:
        # Write back with readable formatting
        print(f"\nWriting optimized data back to {file_path}...")
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(formatted_content)
        print("Done!")
    else:
        print(f"\n[DRY RUN] No changes written. Run without --dry-run to apply.")

    return {
        'original_elements': original_count,
        'deleted_elements': deleted_count,
        'remaining_elements': len(data['elements']),
        'original_size': original_size,
        'optimized_size': formatted_size,
        'minified_size': optimized_size,
        'savings': savings,
        'savings_pct': savings_pct,
    }


def main():
    if len(sys.argv) < 2:
        print("Usage: python optimize_excalidraw.py <path-to-excalidraw-file> [--dry-run]")
        print("\nOptions:")
        print("  --dry-run    Analyze without modifying the file")
        sys.exit(1)

    file_path = sys.argv[1]
    dry_run = '--dry-run' in sys.argv

    optimize_excalidraw(file_path, dry_run)


if __name__ == "__main__":
    main()
